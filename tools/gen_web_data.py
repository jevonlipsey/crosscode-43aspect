#!/usr/bin/env python3
"""Writes the browser patcher's data file from tools/patch43.py, so the web and CLI patches cannot drift apart.
    python3 -I tools/gen_web_data.py OUT.js       (tools/build_web.sh writes web/dist/cc43-data.js)
Needs no game files: the edit list and the known hashes are constants in patch43.py.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import patch43 as P

def s(b):
    t = b.decode('ascii')  # every edit is plain ASCII, so the browser can work on a 1-byte-per-char string
    assert t.encode('ascii') == b
    return t

data = {
    'version': P.VERSION,
    'pristine': P.PRISTINE,
    'patched': P.PATCHED,
    'width': P.W, 'height': P.H,
    'maxBytes': 1024 * 1024,
    'edits': [[s(old), s(new), n] for old, new, n in P.EDITS],
}
js = ('/* generated by tools/gen_web_data.py from tools/patch43.py; do not edit */\n'
      'globalThis.CC43Data = ' + json.dumps(data, indent=1) + ';\n')
if len(sys.argv) != 2: sys.exit(__doc__)
with open(sys.argv[1], 'w', encoding='ascii', newline='\n') as f: f.write(js)
print('wrote', sys.argv[1], len(js), 'bytes; patch', P.VERSION, 'edits', len(P.EDITS))
